/**
 * Create a post and optionally link target account destinations.
 *
 * @param input Post content, status, media, and target accounts
 * @returns The created Post
 */
export async function createPost(input: CreatePostInput): Promise<Post> {
  const destIds = input.destination_account_ids ?? input.account_ids ?? [];
  const payload = {
    id: input.id,
    content: input.content,
    media_urls: input.media_urls ?? [],
    status: input.status,
    scheduled_for: input.scheduled_for,
    created_at: input.created_at,
    format: input.format ?? 'post',
    destination_account_ids: destIds,
  };
  return await safeInvoke<Post>('create_post', { input: payload });
}

