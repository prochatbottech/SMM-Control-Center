/**
 * Create a new social media account in the local database.
 * The plain token is encrypted with AES-256-GCM via the OS Keyring master key
 * before being saved to SQLite.
 *
 * @param input Account details (platform, name, token)
 * @returns The created Account with assigned UUID, timestamp and masked token
 * @throws Error with message from Rust backend if validation or encryption fails
 */
export async function createAccount(input: CreateAccountInput): Promise<Account> {
  const rawToken = input.token ?? input.encrypted_token ?? '';
  const payload = {
    id: input.id,
    platform: input.platform,
    name: input.name,
    encrypted_token: rawToken,
    created_at: input.created_at,
  };
  return await safeInvoke<Account>('create_account', { input: payload });
}

/**
 * Retrieve all registered accounts ordered by creation date descending.
 * Real tokens are excluded from the response and safe masks are returned.
 *
 * @returns Array of accounts with masked tokens
 */
export async function getAccounts(): Promise<Account[]> {
  return await safeInvoke<Account[]>('get_accounts');
}

/**
 * Find an account by its unique UUID identifier.
 * Real tokens are excluded from the response.
 *
 * @param id UUID string
 * @returns The account with masked token or null if not found
 */
export async function getAccountById(id: string): Promise<Account | null> {
  return await safeInvoke<Account | null>('get_account_by_id', { id });
}

/**
 * Delete an account by its UUID.
 * INVARIANT: Automatically triggers ON DELETE CASCADE for any related entries
 * in `post_destinations`.
 *
 * @param id UUID string
 * @returns DeleteResult indicating success and the ID
 */
export async function deleteAccount(id: string): Promise<DeleteResult> {
  return await safeInvoke<DeleteResult>('delete_account', { id });
}

