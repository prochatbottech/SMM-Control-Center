import { invoke } from '@tauri-apps/api/core';

/**
 * Supported platform types for multi-accounting
 */
export type Platform = 'vk' | 'tg' | 'ok' | 'instagram' | string;

/**
 * Status of a post in the scheduled posting pipeline
 */
export type PostStatus =
  | 'draft'
  | 'scheduled'
  | 'publishing'
  | 'published'
  | 'partially_published'
  | 'failed';

/**
 * Status of an individual post destination
 */
export type PostDestinationStatus = 'pending' | 'published' | 'failed';

/**
 * Detailed destination info attached to a post
 */
export interface DestinationInfo {
  account_id: string;
  status: PostDestinationStatus;
  error_log?: string | null;
}

/**
 * Account contract matching `accounts` table in SQLite
 * INVARIANT: `encrypted_token` is excluded from frontend serialization for security.
 * The UI can use `masked_token` (e.g. "vk_***123") for safe display.
 */
export interface Account {
  id: string; // UUID
  platform: Platform;
  name: string;
  encrypted_token?: string | null; // Omitted or null on frontend for security
  masked_token?: string; // Display mask (e.g. "vk_***123")
  created_at: number; // Unix timestamp in seconds
  auth_type?: string | null; // 'oauth' | 'vk_id' | 'tg_session'
  target_id?: string | null; // VK owner_id / Telegram chat_id / OK gid
  target_title?: string | null; // Community / channel / group name
  owner_external_id?: string | null; // Authorizing user id
}

/**
 * Input payload for creating a new account.
 * `token` accepts the raw/plain token from the user; it will be encrypted
 * with AES-256-GCM using the master key from the OS Keyring before storage.
 */
export interface CreateAccountInput {
  id?: string; // Optional UUID (generated by backend if omitted)
  platform: Platform;
  name: string;
  token?: string; // Plain OAuth access token to be encrypted
  encrypted_token?: string; // Alias for backward compatibility
  created_at?: number; // Optional Unix timestamp in seconds
}

/**
 * Post contract matching `posts` table in SQLite
 */
export interface Post {
  id: string; // UUID
  content: string;
  media_urls: string[];
  status: PostStatus;
  scheduled_for: number | null; // Unix timestamp in seconds, null for drafts
  created_at: number; // Unix timestamp in seconds
  format: 'post' | 'article'; // Delivery format: regular post or Telegram rich article
  destination_account_ids: string[];
  destinations?: DestinationInfo[];
}

/**
 * Input payload for creating a new post
 */
export interface CreatePostInput {
  id?: string; // Optional UUID
  content: string;
  media_urls?: string[];
  status?: PostStatus;
  scheduled_for?: number | null;
  created_at?: number;
  format?: 'post' | 'article';
  destination_account_ids?: string[];
  account_ids?: string[]; // Alias for destination_account_ids
}

/**
 * Destination relationship mapping
 */
export interface PostDestination {
  post_id: string;
  account_id: string;
  status: PostDestinationStatus;
  error_log?: string | null;
}

/**
 * Response for deletion operations
 */
export interface DeleteResult {
  deleted: boolean;
  id: string;
}

function formatError(err: unknown): Error {
  if (err instanceof Error) {
    return err;
  }
  if (typeof err === 'string') {
    return new Error(err);
  }
  if (err && typeof err === 'object') {
    if ('message' in err && typeof (err as any).message === 'string') {
      return new Error((err as any).message);
    }
    return new Error(JSON.stringify(err));
  }
  return new Error(String(err));
}

async function safeInvoke<T>(cmd: string, args?: Record<string, unknown>): Promise<T> {
  try {
    return await invoke<T>(cmd, args);
  } catch (err) {
    throw formatError(err);
  }
}

